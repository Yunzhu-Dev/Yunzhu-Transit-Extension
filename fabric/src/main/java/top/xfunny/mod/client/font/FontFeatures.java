    public static boolean isSupportedTag(String tag) {
        return tag != null && (tag.matches("ss(0[1-9]|1[0-9]|20)") || tag.matches("cv(0[1-9]|[1-9][0-9])"));
    }

    public static FontFeature[] normalize(FontFeature... features) {
        Objects.requireNonNull(features, "features");
        final Map<String, FontFeature> sorted = new TreeMap<>();
        for (FontFeature feature : features) {
            Objects.requireNonNull(feature, "feature");
            final FontFeature previous = sorted.put(feature.getTag(), feature);
            if (previous != null && previous.getVariant() != feature.getVariant()) {
                throw new IllegalArgumentException("Conflicting variants for " + feature.getTag());
            }
        }
        return sorted.values().toArray(new FontFeature[0]);
    }

    private static FontFeature cv(FontFeature feature, int variant) {
        return new FontFeature(feature.getTag(), variant);
    }
